    private void btnCadastrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCadastrarActionPerformed
        
        if (!isDadosValidos()) {
        return;
        }
        
        try {
            String nome = txtNome.getText();
            String cpf = txtCpf.getText();
            String tel = txtTelefone.getText(); 
            String end = txtRua.getText();     
            String num = txtNumero.getText();
            String cidade = txtCidade.getText();
            String estado = txtEstado.getText();

            Cliente cliente = new Cliente(nome, cpf, tel, end, num, cidade, estado);
            Boolean sucesso = clienteDAO.cadastrar(cliente);

            if (sucesso) {
                javax.swing.JOptionPane.showMessageDialog(this, "Cadastrado com sucesso!", "Sucesso", javax.swing.JOptionPane.INFORMATION_MESSAGE);
                limparCampos(); 
                atualizarTabela();
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "CPF já existe!", "Erro", javax.swing.JOptionPane.ERROR_MESSAGE);
            }
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Erro ao cadastrar. Verifique os dados.", "Erro", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnCadastrarActionPerformed

    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        
        try {
            
            Long cpf = Long.parseLong(txtCpf.getText().trim());

            int confirmacao = javax.swing.JOptionPane.showConfirmDialog(this, "Tem certeza que deseja excluir?", "Confirmação", javax.swing.JOptionPane.YES_NO_OPTION);

            if (confirmacao == javax.swing.JOptionPane.YES_OPTION) {
                clienteDAO.excluir(cpf);
                javax.swing.JOptionPane.showMessageDialog(this, "Cliente excluído com sucesso!");
                limparCampos();
                atualizarTabela();
            }
        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Por favor, digite um CPF válido para excluir.", "Erro", javax.swing.JOptionPane.WARNING_MESSAGE);
        }
    }//GEN-LAST:event_btnExcluirActionPerformed

    private void btnAtualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAtualizarActionPerformed
        
        if (!isDadosValidos()) {
        return;
        }
        
        try {
            String nome = txtNome.getText();
            String cpf = txtCpf.getText();
            String tel = txtTelefone.getText();
            String end = txtRua.getText();
            String num = txtNumero.getText();
            String cidade = txtCidade.getText();
            String estado = txtEstado.getText();

            Cliente cliente = new Cliente(nome, cpf, tel, end, num, cidade, estado);

            clienteDAO.alterar(cliente);

            javax.swing.JOptionPane.showMessageDialog(this, "Dados atualizados com sucesso!", "Sucesso", javax.swing.JOptionPane.INFORMATION_MESSAGE);
            limparCampos();
            atualizarTabela();
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Erro ao atualizar. Verifique os dados.", "Erro", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnAtualizarActionPerformed

